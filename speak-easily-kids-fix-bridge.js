  function transformQuestion(q) {
    return {
      original: q.q || "",
      paraphrased: q.hint || "",
      vocab: q.wordBank.split(",").map(function (w) {
        var word = w.trim();
        return { word: word, definition: WORD_DEFS[word] || "Topic word — learn it and use it in your answer." };
      }),
      possibleAnswers: [q.model || ""],
      hint: q.hint || "",
      ladder: normaliseLadder(q.ladder || [])
    };
  }

  /* ── normalise the follow-up ladder (alternating ["Probe", "prompt", ...] → {label, text}) ── */
  function normaliseLadder(alt) {
    if (!Array.isArray(alt)) return [];
    var steps = [];
    for (var i = 0; i < alt.length; i += 2) {
      var label = alt[i] || "";
      var text = alt[i + 1] || "";
      steps.push({ label: label, text: text });
    }
    return steps;
  }

  function transformTopics() {
    var incoming = [];
    var topics = window.SPEAKEASILYKIDS && window.SPEAKEASILYKIDS.topics ? window.SPEAKEASILYKIDS.topics : [];
    topics.forEach(function (topic) {
      var slug = SLUG_MAP[topic.slug] || topic.slug.replace(/-/g, "");
      var mapped = {
        slug: slug,
        title: topic.title,
        category: topic.category,
        questions: []
      };
      (topic.questions || []).forEach(function (q) {
        mapped.questions.push(transformQuestion(q));
      });
      incoming.push(mapped);
    });
    return incoming;
  }

  function mergeIntoLessonData() {
    if (!window.lessonData) return;
    var incoming = transformTopics();
    var existingBySlug = {};
    (window.lessonData || []).forEach(function (cat) {
      (cat.topics || []).forEach(function (t) { existingBySlug[t.slug] = t; });
    });
    incoming.forEach(function (newTopic) {
      var slug = newTopic.slug;
      var existingTopic = existingBySlug[slug];
      if (existingTopic) {
        // Replace the existing topic in its category's topics array (in place)
        var cat = (window.lessonData || []).find(function (c) { return c.topics.some(function (t) { return t.slug === slug; }); });
        if (cat) {
          var idx = cat.topics.findIndex(function (t) { return t.slug === slug; });
          if (idx >= 0) { cat.topics[idx] = newTopic; }
        }
        existingBySlug[slug] = newTopic;
      } else {
        var cat = (window.lessonData || []).find(function (c) { return c.category === newTopic.category; });
        if (!cat) {
          cat = { category: newTopic.category, topics: [] };
          (window.lessonData || []).push(cat);
        }
        cat.topics.push(newTopic);
        existingBySlug[slug] = newTopic;
      }
    });
  }

  function onLoad() {
    if (window.SPEAKEASILYKIDS && window.lessonData) {
      mergeIntoLessonData();
    } else {
      setTimeout(onLoad, 200);
    }
  }
  onLoad();
